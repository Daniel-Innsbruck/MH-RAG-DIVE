from langchain_core.messages import HumanMessage, AIMessage
from src.config_manager import load_config
from src.logger import logger
from src.qa_chains.shared import (
    get_vector_store, get_filtered_history, format_history_to_string,
    get_llm_connector, llm_invoke_with_retry, conversation_store
)

def baseline_rag(question: str, thread_id: str):
    """
    Executes a baseline Retrieval-Augmented Generation (RAG) pipeline.

    This function represents the base configuration by relying on a single retrieval step.
    Based on a user query, it searches the vector database once, combines the retrieved
    chunks with the chat history, and prompts the LLM to generate a direct answer.
    
    Args:
        question (str): The user's input question.
        thread_id (str): The unique identifier for the conversation thread.

    Returns:
        dict: A dictionary containing:
            - 'answer' (str): The final answer generated by the LLM.
            - 'context' (list of str): All retrieved document chunks used as context.

    Raises:
        Exception: If the LLM returns an empty response or an error occurs during execution.
    """
    try:
        config = load_config()["rag_settings"]
        llm = get_llm_connector(config["llm_model"])
        vector_store = get_vector_store(config)

        if thread_id not in conversation_store:
            conversation_store[thread_id] = []

        chat_history = get_filtered_history(thread_id, config)
        history_text = format_history_to_string(chat_history)

        k = config["k_chunks"]
        retrieved_docs = vector_store.similarity_search(question, k=k)
        docs_content = "\n\n".join(doc.page_content for doc in retrieved_docs)

        full_prompt_text = f"""{config["system_prompt"]}\nChat History:\n{history_text}\nContext:\n{docs_content}\nQuestion: {question}"""

        response_text = llm_invoke_with_retry(llm, full_prompt_text)
        if not response_text:
            raise Exception("LLM returned no response.")

        conversation_store[thread_id].extend([HumanMessage(content=question), AIMessage(content=response_text)])

        return {"answer": response_text, "context": [doc.page_content for doc in retrieved_docs]}
    except Exception as e:
        logger.error(f"Error in baseline_rag: {str(e)}", exc_info=True)
        raise e