import json
import re

from langchain_core.messages import HumanMessage, AIMessage
from src.config_manager import load_config
from src.logger import logger
from src.qa_chains.shared import (
    get_vector_store,
    get_filtered_history,
    format_history_to_string,
    get_llm_connector,
    llm_invoke_with_retry,
    conversation_store
)

def agentic_rag(question: str, thread_id: str):
    """
    Executes an Agentic Retrieval-Augmented Generation (RAG) loop.

    This function implements an agentic setup that allows the system to perform
    multiple retrieval steps instead of relying on a single retrieval step. The LLM
    can dynamically decide whether to 'SEARCH' the vector database for more context
    or 'ANSWER' the user's query with the accumulated context.

    Args:
        question (str): The user's input question.
        thread_id (str): The unique identifier for the conversation thread.

    Returns:
        dict: A dictionary containing:
            - 'answer' (str): The final answer generated by the LLM.
            - 'context' (list of str): All retrieved document chunks used to formulate the answer.

    Raises:
        Exception: If the LLM returns an empty response.
    """
    config_full = load_config()
    config = config_full["rag_settings"]

    max_hops = config["max_hops"]
    k_chunks = config["k_chunks"]

    llm = get_llm_connector(config["llm_model"])
    vector_store = get_vector_store(config)

    if thread_id not in conversation_store:
        conversation_store[thread_id] = []

    chat_history = get_filtered_history(thread_id, config)
    history_text = format_history_to_string(chat_history)

    context_memory = []
    all_retrieved_contents = []
    seen_chunk_hashes = set()  # To avoid inserting exact duplicate chunks

    agent_system_prompt = config["agentic_system_prompt"]

    for hop in range(max_hops):
        logger.info(f"[Thread {thread_id}] Agentic Hop {hop + 1}/{max_hops} starting...")

        context_str = "\n\n---\n\n".join(context_memory) if context_memory else "No documents retrieved yet."

        user_prompt_template=config["agentic_user_prompt"]

        user_message = user_prompt_template.format(
            history_text=history_text,
            question=question,
            context_str=context_str
        )
        full_prompt = f"{agent_system_prompt}\n\n{user_message}"

        response_text = llm_invoke_with_retry(llm, full_prompt)
        if not response_text:
            raise Exception("LLM returned no response.")

        try:
            clean_text = response_text.strip()
            if clean_text.startswith("```"):
                clean_text = re.sub(r'^```(?:json)?\s*|\s*```$', '', clean_text, flags=re.MULTILINE)

            json_match = re.search(r'(\{.*\})', clean_text, re.DOTALL)
            json_str = json_match.group(1) if json_match else clean_text
            parsed = json.loads(json_str)

            # Ensure the LLM generated a dictionary and not a list
            if not isinstance(parsed, dict):
                raise ValueError("Parsed JSON is not a dictionary.")

        except (json.JSONDecodeError, ValueError) as e:
            logger.error(f"[Hop {hop + 1}] Failed to parse JSON. Error: {str(e)}. Raw output: {response_text}")

            # Emergency extraction of the answer with fallback
            fallback_match = re.search(r'"final_answer"\s*:\s*"([^"]+)"', response_text)
            fallback_answer = fallback_match.group(
                1) if fallback_match else "Error: Agent produced invalid format and could not be parsed."

            conversation_store[thread_id].extend([HumanMessage(content=question), AIMessage(content=fallback_answer)])
            return {"answer": fallback_answer, "context": all_retrieved_contents}

        thought = parsed.get("thought", "")
        action = parsed.get("action", "ANSWER")
        logger.info(f"[Hop {hop + 1}] Thought: {thought} | Action: {action}")

        if action == "SEARCH":
            search_query = parsed.get("search_query", question)
            logger.info(f"[Hop {hop + 1}] Searching ChromaDB for: '{search_query}' (k={k_chunks})")

            # Fetch k=config["k_chunks"] from the vector store
            retrieved_docs = vector_store.similarity_search(search_query, k=k_chunks)

            new_info_found = False
            for doc in retrieved_docs:
                chunk_hash = hash(doc.page_content)
                if chunk_hash not in seen_chunk_hashes:
                    seen_chunk_hashes.add(chunk_hash)
                    context_memory.append(doc.page_content)
                    all_retrieved_contents.append(doc.page_content)
                    new_info_found = True

            if not new_info_found:
                logger.warning(f"[Hop {hop + 1}] Search returned identical chunks. Prompting to stop or change query.")
                context_memory.append(
                    f"System Note: Your search for '{search_query}' returned exactly the same chunks you already have. You must ANSWER now or use a completely different search query.")

        elif action == "ANSWER":
            final_answer = parsed.get("final_answer", "I could not generate an answer.")
            conversation_store[thread_id].extend([HumanMessage(content=question), AIMessage(content=final_answer)])
            return {"answer": final_answer, "context": all_retrieved_contents}
        else:
            logger.warning(f"[Hop {hop + 1}] Unknown action '{action}'. Forcing search.")
            context_memory.append(f"System Note: Invalid action '{action}'. Use 'SEARCH' or 'ANSWER'.")

    # Fallback when max_hops are reached
    logger.warning(f"[Thread {thread_id}] Max hops ({max_hops}) reached. Forcing answer.")

    context_str = "\n\n---\n\n".join(context_memory) if context_memory else "No documents retrieved."
    fallback_prompt = f"""{config.get("system_prompt")}
    Chat History:
    {history_text}
    Context:
    {context_str}
    Question: {question}
    """
    final_answer = llm_invoke_with_retry(llm, fallback_prompt)
    if not final_answer:
        final_answer = "Error: Fallback generation failed due to safety filters or timeout."

    conversation_store[thread_id].extend([HumanMessage(content=question), AIMessage(content=final_answer)])

    return {
        "answer": final_answer,
        "context": all_retrieved_contents
    }