import logging
from conversation_validator.utils.parser_validation import LLMResponseParser
from conversation_validator import templatesValidation as templates

logger = logging.getLogger(__name__)
parser = LLMResponseParser()


def send_request_to_LLM_validation(prompt, val_llm, max_retries: int = 3):
    """
    Sends the prompt to the Conversation Validator (CV) LLM.

    Retries the request if the LLM returns invalid JSON or if a temporary error occurs.
    Includes a fail-fast mechanism for critical configuration errors (e.g., invalid API keys).

    Args:
        prompt (str): The validation prompt to send to the CV.
        val_llm: The LLM wrapper instance used for validation.
        max_retries (int): Maximum number of retry attempts. Default is 3.

    Returns:
        dict: The parsed validation response, or None if validation fails after all retries.
    """
    for attempt in range(max_retries):
        try:
            llm_response = val_llm.prompt(prompt)
            response = parser.parse_and_validate_validation(llm_response)

            if response is not None:
                return response

            logger.warning(
                f"[Validator] Attempt {attempt + 1}/{max_retries}: "
                f"Invalid JSON received. Retrying validation..."
            )

        except Exception as e:
            error_msg = str(e).lower()
            if any(fatal_code in error_msg for fatal_code in
                   ["401", "403", "404", "model_not_found", "invalid_request_error"]):
                logger.error(f"[Validator] FATAL CONFIGURATION ERROR: {e}")
                raise ValueError(f"Aborting due to critical API error: {e}")

            logger.warning(
                f"[Validator] Attempt {attempt + 1}/{max_retries} failed with error: {e}. "
                f"Retrying..."
            )

    logger.error(f"[Validator] Validation ultimately failed after {max_retries} attempts.")
    return None


def validate_init_prompt_all_in_one(question, document, val_llm, max_retries: int = 3):
    """
    Validates the initial turn (Turn 0) generated by the Conversation Generator.

    In addition to baseline criteria, the Conversation Validator verifies Query Type
    Alignment and Multi-Hop Integrity to ensure both context chunks are genuinely
    required to answer the question.

    Args:
        question (dict): The output bundle generated by the Conversation Generator.
        document (list or str): The initial multi-hop context chunks provided by the CD.
        val_llm: The LLM wrapper instance used for validation.
        max_retries (int): Maximum number of validation retries.

    Returns:
        dict: A dictionary containing 'correct' (bool), 'reason' (str), and the 'prompt_used'.
    """
    if question is None:
        return {
            "correct": False,
            "reason": "Generator output was invalid or could not be parsed.",
            "prompt_used": "N/A"
        }

    question_dict = {
        'rag_input': question.get('rag_input', question.get('question')),
        'question': question.get('question', ''),
        'answer': question.get('answer', ''),
        'type': question.get('type', 'Initial'),
        'logic_type': question.get('logic_type', ''),
        'multi_hop_flag': question.get('multi_hop_flag', 1),
        'bridging_topic': question.get('bridging_topic', '')
    }

    validate_prompt = templates.VALIDATION_PROMPTS['validate_init_prompt'].format(
        question=str(question_dict),
        document=str(document)
    )

    answer = send_request_to_LLM_validation(validate_prompt, val_llm, max_retries=max_retries)
    if answer is None:
        return {"correct": False, "reason": "Validation LLM failed after max retries.", "prompt_used": validate_prompt}

    if isinstance(answer, dict):
        answer["prompt_used"] = validate_prompt
    return answer


def validate_follow_up_question_all_in_one(question, history, current_active_context, val_llm, max_retries: int = 3):
    """
    Validates a follow-up conversation turn generated by the Conversation Generator.

    The Conversation Validator determines whether the new turn logically follows the
    conversation history.

    Args:
        question (dict): The output bundle generated by the Conversation Generator.
        history (str): The preceding conversational exchange.
        current_active_context (list or str): The current, potentially expanded context scope.
        val_llm: The LLM wrapper instance used for validation.
        max_retries (int): Maximum number of validation retries.

    Returns:
        dict: A dictionary containing 'correct' (bool), 'reason' (str), and the 'prompt_used'.
    """
    if question is None:
        return {
            "correct": False,
            "reason": "Generator output was invalid or could not be parsed.",
            "prompt_used": "N/A"
        }

    question_dict = {
        'rag_input': question.get('rag_input', ''),
        'type': question.get('type', ''),
        'question': question.get('question', ''),
        'answer': question.get('answer', ''),
    }

    validate_prompt = templates.VALIDATION_PROMPTS["validate_follow_up_prompt"].format(
        question=str(question_dict),
        conversation_history=str(history),
        active_context=current_active_context
    )

    answer = send_request_to_LLM_validation(validate_prompt, val_llm, max_retries=max_retries)
    if answer is None:
        return {"correct": False, "reason": "Validation LLM failed after max retries.", "prompt_used": validate_prompt}

    if isinstance(answer, dict):
        answer["prompt_used"] = validate_prompt
    return answer